import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {randomUUID} from 'node:crypto';
if(!process.env.FIRESTORE_EMULATOR_HOST||!process.env.FIREBASE_AUTH_EMULATOR_HOST)throw Error('This test is emulator-only. Refusing to access production.');
const require=createRequire(new URL('../functions/index.js',import.meta.url));
const {initializeApp:adminApp,deleteApp:deleteAdmin}=require('firebase-admin/app');
const {getAuth:adminAuth}=require('firebase-admin/auth');const {getFirestore:adminFirestore,FieldValue}=require('firebase-admin/firestore');
const admin=adminApp({projectId:'demo-pagegenie-recovery'}),db=adminFirestore(admin),auth=adminAuth(admin);
const {accountRecovery,purgeAccount,assertAccountActive,RECOVERY_MS}=await import('../functions/account-lifecycle.js');
const {initializeApp,deleteApp}=await import('firebase/app');
const {getAuth,connectAuthEmulator,signInWithEmailAndPassword}=await import('firebase/auth');
const {getFirestore,connectFirestoreEmulator,doc,getDoc,setDoc,serverTimestamp,terminate}=await import('firebase/firestore');
const password=randomUUID();const uid='dummy-recovery',other='dummy-other';
await auth.createUser({uid,email:'recovery@example.invalid',emailVerified:true,password});
await auth.createUser({uid:other,email:'other@example.invalid',emailVerified:true,password});
const project='dummy-project-recovery',otherProject='dummy-project-other';
await db.doc(`users/${uid}/projects/${project}`).set({name:'Recovery QA',draft:'dummy website',updatedAt:FieldValue.serverTimestamp()});
await db.doc(`users/${uid}/logoProjects/${project}/versions/v1`).set({image:'dummy-logo'});
await db.doc(`users/${other}/projects/${otherProject}`).set({name:'Other account',draft:'unchanged'});
await db.doc('publishedSites/'+project).set({ownerId:uid,name:'Recovery QA',draft:'dummy-public-site'});
await db.doc('publishedSites/'+otherProject).set({ownerId:other,name:'Other account',draft:'unchanged'});
const client=initializeApp({projectId:'demo-pagegenie-recovery',apiKey:'fake-api-key',authDomain:'localhost'});
const clientAuth=getAuth(client);connectAuthEmulator(clientAuth,'http://'+process.env.FIREBASE_AUTH_EMULATOR_HOST,{disableWarnings:true});
const clientDb=getFirestore(client);const [host,port]=process.env.FIRESTORE_EMULATOR_HOST.split(':');connectFirestoreEmulator(clientDb,host,Number(port));
await signInWithEmailAndPassword(clientAuth,'recovery@example.invalid',password);
const call=async(action,extra={})=>accountRecovery.run({auth:{uid,token:await clientAuth.currentUser.getIdTokenResult().then(r=>r.claims)},data:{action,...extra}});
const publicRef=doc(clientDb,'publishedSites',project),privateRef=doc(clientDb,'users',uid,'projects',project);
assert.equal((await getDoc(publicRef)).exists(),true);
await assert.rejects(accountRecovery.run({data:{action:'schedule',confirmation:'DELETE MY ACCOUNT'}}));
await assert.rejects(call('schedule',{confirmation:'wrong'}));
const scheduled=await call('schedule',{confirmation:'DELETE MY ACCOUNT',uid:other,now:0});
assert.ok(scheduled.deleteAfter>Date.now()+RECOVERY_MS-10000);assert.equal((await db.doc('accountLifecycle/'+other).get()).exists,false);
await assert.rejects(getDoc(publicRef),e=>e.code==='permission-denied');
assert.equal((await getDoc(privateRef)).data().draft,'dummy website');
await assert.rejects(setDoc(privateRef,{name:'Blocked edit',draft:'changed',updatedAt:serverTimestamp()}),e=>e.code==='permission-denied');
await assert.rejects(assertAccountActive(uid,db));
await call('recover');assert.equal((await getDoc(publicRef)).exists(),true);
assert.equal((await db.doc(`users/${uid}/logoProjects/${project}/versions/v1`).get()).data().image,'dummy-logo');
await db.doc(`users/${uid}/billing/${project}`).set({status:'cancelled',paid:false});
await assert.rejects(call('schedule',{confirmation:'DELETE MY ACCOUNT'}),/billing/);
assert.equal((await db.doc('accountLifecycle/'+uid).get()).data().status,'active');
await db.doc(`users/${uid}/billing/${project}`).delete();
await db.doc('domainConnections/dummy.invalid').set({uid,status:'disconnected'});
await assert.rejects(call('schedule',{confirmation:'DELETE MY ACCOUNT'}),/domain/);
await db.doc('domainConnections/dummy.invalid').delete();
const next=await call('schedule',{confirmation:'DELETE MY ACCOUNT'});
assert.equal((await purgeAccount(uid,{db,auth,now:next.deleteAfter-1})).purged,false);
const deletion=await purgeAccount(uid,{db,auth,now:next.deleteAfter+1});assert.equal(deletion.purged,true);
await assert.rejects(auth.getUser(uid),e=>e.code==='auth/user-not-found');
assert.equal((await db.doc(`users/${uid}/projects/${project}`).get()).exists,false);
assert.equal((await db.doc(`users/${uid}/logoProjects/${project}/versions/v1`).get()).exists,false);
assert.equal((await db.doc('publishedSites/'+project).get()).exists,false);
assert.equal((await db.doc(`users/${other}/projects/${otherProject}`).get()).data().draft,'unchanged');
assert.equal((await auth.getUser(other)).uid,other);
await assert.rejects(assertAccountActive(uid,db));
console.log(JSON.stringify({environment:'isolated Firebase emulators',passed:true,checks:['verified owner and explicit confirmation','caller cannot target another UID or shorten recovery','public site unavailable during recovery','private content retained; edits blocked','account and logo recovery','billing and domain records stop deletion','30-day deadline enforced','nested content and Auth permanently removed after simulated expiry','other account unchanged','old-token guard remains blocked']},null,2));
await terminate(clientDb);await deleteApp(client);await deleteAdmin(admin);
