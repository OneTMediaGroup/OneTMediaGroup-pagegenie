import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
if(!process.env.FIRESTORE_EMULATOR_HOST)throw Error('Requires isolated Firestore emulator');
const require=createRequire(new URL('../functions/index.js',import.meta.url));
const {initializeApp}=require('firebase-admin/app');initializeApp();
const {getFirestore}=require('firebase-admin/firestore'),db=getFirestore();
const {saveProjectDraft}=await import('../functions/project-save.js');
const now=Date.now(),id=n=>'aaaaaaaa-aaaa-aaaa-aaaa-'+String(n).padStart(12,'0');
const request=(uid,n,verified=true)=>({auth:{uid,token:{email_verified:verified}},data:{projectId:id(n),name:'Northline test',draft:'{"logo":"preserved","contactPhone":"+19055550100"}'}});
const save=r=>saveProjectDraft({db,request:r,now});
await assert.rejects(save({data:request('a',1).data}),e=>e.code==='unauthenticated');
for(const data of [{projectId:'../escape'},{draft:'not json'},{draft:'[]'},{draft:'x'.repeat(650001)},{name:''}])await assert.rejects(save({...request('a',1),data:{...request('a',1).data,...data}}),e=>e.code==='invalid-argument');
const concurrent=await Promise.allSettled(Array.from({length:5},(_,i)=>save(request('unverified',i,false))));
assert.equal(concurrent.filter(r=>r.status==='fulfilled').length,3);
assert.equal((await db.collection('users/unverified/projects').get()).size,3);
await save(request('daily',1));await db.doc('projectSaveLimits/daily').set({day:new Date(now).toISOString().slice(0,10),created:20});
await assert.rejects(save(request('daily',2)),e=>e.code==='resource-exhausted');
await save(request('daily',1));
assert.equal(JSON.parse((await db.doc('users/daily/projects/'+id(1)).get()).data().draft).logo,'preserved');
await db.doc('projectSaveLimits/daily').set({minute:Math.floor(now/60000),writes:60});
await assert.rejects(save(request('daily',1)),e=>e.code==='resource-exhausted');
await db.doc('accountLifecycle/deleted').set({status:'deleted'});
await assert.rejects(save(request('deleted',1)),e=>e.code==='failed-precondition');
const batch=db.batch();for(let i=0;i<100;i++)batch.set(db.doc('users/full/projects/'+id(i)),{name:'existing',draft:'{}'});await batch.commit();
await assert.rejects(save(request('full',101)),e=>e.code==='resource-exhausted');await save(request('full',1));
await save(request('separate',1));assert((await db.doc('users/separate/projects/'+id(1)).get()).exists);
console.log('PASS: atomic creation limit, daily and minute limits, existing logo/contact preservation, account isolation, deleted-account refusal and payload validation.');
